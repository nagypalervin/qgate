// csharp-analysis: "A file that stops being generated"
#[test]
fn a_file_that_stops_being_generated_is_new() {
    let new_error = |path: &str| {
        format!(
            "error   {path}:3  Main.Run(int): new function, cyclomatic complexity 31  \
             [complexity/cyclomatic-new]\n"
        )
    };
    // Renamed from a generated name.
    let repo = Repo::new();
    repo.write("Forms/Main.Designer.cs", complex_class("Main"));
    repo.commit("base");
    repo.git(&["checkout", "-q", "-b", "feature"]);
    repo.git(&["mv", "Forms/Main.Designer.cs", "Forms/Main.cs"]);
    repo.commit("rename");
    let out = repo.qgate(&["--base", "main", "--fail-on", "never"]);
    assert_eq!(stdout(&out), new_error("Forms/Main.cs"), "{}", stderr(&out));
    // Its header removed.
    let repo = Repo::new();
    repo.write(
        "src/Main.cs",
        format!("// <auto-generated />\n{}", complex_class("Main")),
    );
    repo.commit("base");
    repo.git(&["checkout", "-q", "-b", "feature"]);
    repo.write("src/Main.cs", complex_class("Main"));
    repo.commit("hand-written");
    let out = repo.qgate(&["--base", "main", "--fail-on", "never"]);
    assert_eq!(stdout(&out), new_error("src/Main.cs"), "{}", stderr(&out));
}
