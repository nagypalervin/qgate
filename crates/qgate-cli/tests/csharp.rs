//! End-to-end tests for C# in revision mode (`add-csharp-analysis`): the
//! C# scenarios of the `revision-input`, `duplication-analysis` and
//! `csharp-analysis` specs. Each test builds a throwaway git repository
//! and runs the built binary in it, as `revisions.rs` does.

mod support;

use std::fmt::Write as _;

use support::{Repo, stderr, stdout};

/// `Cart.Total(int)` with complexity 2, named on line 5.
const CART_BEFORE: &str = "namespace Shop;

public class Cart
{
    public decimal Total(int d)
    {
        if (d > 0) { return 1; }
        return 0;
    }
}
";

/// The same method with two more `if` statements: complexity 4.
const CART_AFTER: &str = "namespace Shop;

public class Cart
{
    public decimal Total(int d)
    {
        if (d > 0) { return 1; }
        if (d > 5) { return 2; }
        if (d > 9) { return 3; }
        return 0;
    }
}
";

const CART_FINDING: &str = "warning src/Cart.cs:5  Cart.Total(int): cyclomatic complexity 2 -> 4 (+2)  \
                            [complexity/cyclomatic-increase]\n";

/// A class whose one method has complexity 31: an Error wherever it is
/// analyzed.
fn complex_class(name: &str) -> String {
    let ifs = "        if (d > 0) { d--; }\n".repeat(30);
    format!(
        "public class {name}\n{{\n    public int Run(int d)\n    {{\n{ifs}        return d;\n    }}\n}}\n"
    )
}

/// A model built the way EF Core's migrations and snapshots build it, in
/// a method of `class_name`, preceded by `header`.
fn model(header: &str, class_name: &str) -> String {
    let mut entities = String::new();
    for e in ["Order", "Line", "Customer", "Address", "Invoice"] {
        let _ = write!(
            entities,
            "        modelBuilder.Entity(\"Shop.{e}\", b =>\n        {{\n            \
             b.Property<int>(\"Id\").ValueGeneratedOnAdd();\n            \
             b.HasKey(\"Id\");\n            b.ToTable(\"{e}s\");\n        }});\n"
        );
    }
    format!(
        "{header}namespace Shop.Migrations;\n\npartial class {class_name}\n{{\n    \
         protected void BuildModel(ModelBuilder modelBuilder)\n    {{\n{entities}    }}\n}}\n"
    )
}

/// A repository with `CART_BEFORE` committed on `main` and `feature`
/// checked out, which then holds `files` committed.
fn change(files: &[(&str, &str)]) -> Repo {
    let repo = Repo::new();
    repo.write("src/Cart.cs", CART_BEFORE);
    repo.commit("base");
    repo.git(&["checkout", "-q", "-b", "feature"]);
    for (path, contents) in files {
        repo.write(path, contents);
    }
    repo.commit("feature");
    repo
}

// complexity-analysis: "A C# method that got more complex"
#[test]
fn a_csharp_method_got_more_complex() {
    let repo = change(&[("src/Cart.cs", CART_AFTER)]);
    let out = repo.qgate(&["--base", "main"]);
    assert_eq!(stdout(&out), CART_FINDING, "{}", stderr(&out));
    assert_eq!(out.status.code(), Some(0));
}

// revision-input: "C# files"; csharp-analysis: "A file by name"
#[test]
fn generated_and_project_files_are_not_analyzed() {
    let designer = complex_class("Main");
    let repo = change(&[
        ("src/Cart.cs", CART_AFTER),
        ("src/Cart.Designer.cs", &designer),
        ("Forms/Main.Designer.cs", &designer),
        ("src/Shop.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n"),
    ]);
    let out = repo.qgate(&["--base", "main"]);
    assert_eq!(stdout(&out), CART_FINDING, "{}", stderr(&out));
}

#[test]
fn a_generated_header_skips_the_file() {
    let header = "// <auto-generated />\n#nullable disable\n";
    let repo = change(&[(
        "src/Client.cs",
        &format!("{header}{}", complex_class("Client")),
    )]);
    let out = repo.qgate(&["--base", "main"]);
    assert_eq!(stdout(&out), "No regressions found.\n", "{}", stderr(&out));
}

// csharp-analysis: "An EF Core migration"
#[test]
fn ef_core_migrations_report_no_copies() {
    let generated = "// <auto-generated />\n";
    let migration = |header: &str| {
        let repo = Repo::new();
        repo.write("Migrations/20261101_Init.cs", model("", "Init"));
        repo.commit("base");
        repo.git(&["checkout", "-q", "-b", "feature"]);
        repo.write(
            "Migrations/20261113_AddOrders.Designer.cs",
            model(generated, "AddOrders"),
        );
        repo.write(
            "Migrations/AppDbContextModelSnapshot.cs",
            model(header, "AppDbContextModelSnapshot"),
        );
        repo.commit("migration");
        repo.qgate(&["--base", "main"])
    };
    let out = migration(generated);
    assert_eq!(stdout(&out), "No regressions found.\n", "{}", stderr(&out));
    // Without its header, the snapshot is an ordinary file and a copy;
    // the namespace has no tokens and the class name is `$id`, so the copy
    // starts at `partial class`.
    let out = migration("");
    assert!(
        stdout(&out).contains(
            "Migrations/AppDbContextModelSnapshot.cs:3  duplicates Migrations/20261101_Init.cs:3-"
        ),
        "{}",
        stdout(&out)
    );
}

#[test]
fn a_csharp_change_in_the_working_tree() {
    let repo = Repo::new();
    repo.write("src/Cart.cs", CART_BEFORE);
    repo.commit("base");
    repo.write("src/Cart.cs", CART_AFTER);
    let out = repo.qgate(&["--base", "HEAD", "--worktree"]);
    assert_eq!(stdout(&out), CART_FINDING, "{}", stderr(&out));
}

// duplication-analysis: "Copy of an existing C# file"
#[test]
fn copy_of_an_existing_csharp_file() {
    let repo = Repo::new();
    repo.write(
        "src/Utils/Dates.cs",
        include_str!("../../qgate-analyzers/fixtures/duplication/date_helper.cs"),
    );
    repo.commit("base");
    repo.write(
        "src/Orders/Format.cs",
        include_str!("../../qgate-analyzers/fixtures/duplication/renamed_copy.cs"),
    );
    repo.commit("copy");
    let out = repo.qgate(&["--base", "HEAD~1"]);
    assert_eq!(
        stdout(&out),
        "warning src/Orders/Format.cs:10  duplicates src/Utils/Dates.cs:5-12 \
         (lines 10-17, 66 tokens)  [duplication/duplicate-block]\n",
        "{}",
        stderr(&out)
    );
}

/// Sixteen calls that give the same 128 normalized tokens in TypeScript
/// and in C#: `$id . mN ( $id , $lit )`.
fn calls() -> String {
    let mut calls = String::new();
    for n in 1..=16 {
        let _ = writeln!(calls, "        x.m{n}(a, \"s\");");
    }
    calls
}

// duplication-analysis: "The same tokens in two languages"
#[test]
fn copies_are_found_within_one_language_only() {
    let ts = calls();
    let cs = format!("class A\n{{\n    void F()\n    {{\n{}    }}\n}}\n", calls());
    let duplicates = |a: (&str, &str), b: (&str, &str)| {
        let repo = Repo::new();
        repo.write("README.md", "base\n");
        repo.commit("base");
        repo.write(a.0, a.1);
        repo.write(b.0, b.1);
        repo.commit("change");
        let out = repo.qgate(&["--base", "HEAD~1"]);
        assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
        stdout(&out).contains("[duplication/duplicate-block]")
    };
    assert!(duplicates(("src/a.ts", &ts), ("src/b.ts", &ts)));
    assert!(duplicates(("src/A.cs", &cs), ("src/B.cs", &cs)));
    assert!(!duplicates(("src/a.ts", &ts), ("src/B.cs", &cs)));
}
