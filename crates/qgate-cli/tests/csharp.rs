//! End-to-end tests for C# in revision mode (`add-csharp-analysis`): the
//! C# scenarios of the `revision-input`, `duplication-analysis` and
//! `csharp-analysis` specs. Each test builds a throwaway git repository
//! and runs the built binary in it, as `revisions.rs` does.

mod support;

use std::fmt::Write as _;

use support::{Repo, stderr, stdout};

/// `Cart.Total(int)` with complexity 2, named on line 5.
const CART_BEFORE: &str = "namespace Shop;

public class Cart
{
    public decimal Total(int d)
    {
        if (d > 0) { return 1; }
        return 0;
    }
}
";

/// The same method with two more `if` statements: complexity 4.
const CART_AFTER: &str = "namespace Shop;

public class Cart
{
    public decimal Total(int d)
    {
        if (d > 0) { return 1; }
        if (d > 5) { return 2; }
        if (d > 9) { return 3; }
        return 0;
    }
}
";

const CART_FINDING: &str = "warning src/Cart.cs:5  Cart.Total(int): cyclomatic complexity 2 -> 4 (+2)  \
                            [complexity/cyclomatic-increase]\n";

/// A class whose one method has complexity 31: an Error wherever it is
/// analyzed.
fn complex_class(name: &str) -> String {
    let ifs = "        if (d > 0) { d--; }\n".repeat(30);
    format!(
        "public class {name}\n{{\n    public int Run(int d)\n    {{\n{ifs}        return d;\n    }}\n}}\n"
    )
}

/// A model built the way EF Core's migrations and snapshots build it, in
/// a method of `class_name`, preceded by `header`.
fn model(header: &str, class_name: &str) -> String {
    let mut entities = String::new();
    for e in ["Order", "Line", "Customer", "Address", "Invoice"] {
        let _ = write!(
            entities,
            "        modelBuilder.Entity(\"Shop.{e}\", b =>\n        {{\n            \
             b.Property<int>(\"Id\").ValueGeneratedOnAdd();\n            \
             b.HasKey(\"Id\");\n            b.ToTable(\"{e}s\");\n        }});\n"
        );
    }
    format!(
        "{header}namespace Shop.Migrations;\n\npartial class {class_name}\n{{\n    \
         protected void BuildModel(ModelBuilder modelBuilder)\n    {{\n{entities}    }}\n}}\n"
    )
}

/// A repository with `CART_BEFORE` committed on `main` and `feature`
/// checked out, which then holds `files` committed.
fn change(files: &[(&str, &str)]) -> Repo {
    let repo = Repo::new();
    repo.write("src/Cart.cs", CART_BEFORE);
    repo.commit("base");
    repo.git(&["checkout", "-q", "-b", "feature"]);
    for (path, contents) in files {
        repo.write(path, contents);
    }
    repo.commit("feature");
    repo
}

// complexity-analysis: "A C# method that got more complex"
#[test]
fn a_csharp_method_got_more_complex() {
    let repo = change(&[("src/Cart.cs", CART_AFTER)]);
    let out = repo.qgate(&["--base", "main"]);
    assert_eq!(stdout(&out), CART_FINDING, "{}", stderr(&out));
    assert_eq!(out.status.code(), Some(0));
}

// revision-input: "C# files"; csharp-analysis: "A file by name"
#[test]
fn generated_and_project_files_are_not_analyzed() {
    let designer = complex_class("Main");
    let repo = change(&[
        ("src/Cart.cs", CART_AFTER),
        ("src/Cart.Designer.cs", &designer),
        ("Forms/Main.Designer.cs", &designer),
        ("src/Shop.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />\n"),
    ]);
    let out = repo.qgate(&["--base", "main"]);
    assert_eq!(stdout(&out), CART_FINDING, "{}", stderr(&out));
}

