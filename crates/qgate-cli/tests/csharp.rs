// A C# file renamed to TypeScript: its C# code left the C# family and is
// no base for the TypeScript file (design D7). `calls()` is valid C#
// (top-level statements) and TypeScript.
#[test]
fn a_csharp_file_renamed_to_typescript_counts_as_added() {
    let repo = Repo::new();
    repo.write("src/Calls.cs", calls());
    repo.write("src/u.ts", calls());
    repo.commit("base");
    repo.git(&["checkout", "-q", "-b", "feature"]);
    repo.git(&["mv", "src/Calls.cs", "src/calls.ts"]);
    repo.commit("rename");
    let out = repo.qgate(&["--base", "main"]);
    assert!(
        stdout(&out).contains("src/calls.ts:1  duplicates src/u.ts:1-16"),
        "{}{}",
        stdout(&out),
        stderr(&out)
    );
}

