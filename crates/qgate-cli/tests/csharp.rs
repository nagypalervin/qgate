/// Sixteen calls that give the same 128 normalized tokens in TypeScript
/// and in C#: `$id . mN ( $id , $lit )`.
fn calls() -> String {
    let mut calls = String::new();
    for n in 1..=16 {
        let _ = writeln!(calls, "        x.m{n}(a, \"s\");");
    }
    calls
}

// duplication-analysis: "The same tokens in two languages"
#[test]
fn copies_are_found_within_one_language_only() {
    let ts = calls();
    let cs = format!("class A\n{{\n    void F()\n    {{\n{}    }}\n}}\n", calls());
    let duplicates = |a: (&str, &str), b: (&str, &str)| {
        let repo = Repo::new();
        repo.write("README.md", "base\n");
        repo.commit("base");
        repo.write(a.0, a.1);
        repo.write(b.0, b.1);
        repo.commit("change");
        let out = repo.qgate(&["--base", "HEAD~1"]);
        assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
        stdout(&out).contains("[duplication/duplicate-block]")
    };
    assert!(duplicates(("src/a.ts", &ts), ("src/b.ts", &ts)));
    assert!(duplicates(("src/A.cs", &cs), ("src/B.cs", &cs)));
    assert!(!duplicates(("src/a.ts", &ts), ("src/B.cs", &cs)));
}

/// `calls()` in a C# class.
fn cs_calls() -> String {
    format!("class A\n{{\n    void F()\n    {{\n{}    }}\n}}\n", calls())
}

/// Commit `base` on `main`, then apply `change` (path, contents; `None`
/// deletes) on `feature` and run `--base main`.
fn run(base: &[(&str, &str)], change: &[(&str, Option<&str>)]) -> String {
    let repo = Repo::new();
    repo.write("README.md", "base\n");
    for (path, contents) in base {
        repo.write(path, contents);
    }
    repo.commit("base");
    repo.git(&["checkout", "-q", "-b", "feature"]);
    for (path, contents) in change {
        match contents {
            Some(contents) => repo.write(path, contents),
            None => {
                repo.git(&["rm", "-q", path]);
            }
        }
    }
    repo.commit("change");
    let out = repo.qgate(&["--base", "main"]);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    stdout(&out)
}

const COPY_RULE: &str = "[duplication/duplicate-block]";

// duplication-analysis: "The same tokens in two languages", with an
// unchanged file of the other language.
#[test]
fn unchanged_files_of_the_other_language_are_not_compared() {
    let out = run(
        &[("src/B.cs", &cs_calls())],
        &[("src/a.ts", Some(&calls()))],
    );
    assert_eq!(out, "No regressions found.\n");
    let out = run(
        &[("src/b.ts", &calls())],
        &[("src/A.cs", Some(&cs_calls()))],
    );
    assert_eq!(out, "No regressions found.\n");
}

// duplication-analysis: "What existed before" stays within a family: a
// deleted C# file does not make a TypeScript copy old.
#[test]
fn deleted_files_count_only_for_their_language() {
    let out = run(
        &[("src/c.ts", &calls()), ("src/Old.cs", &cs_calls())],
        &[("src/Old.cs", None), ("src/a.ts", Some(&calls()))],
    );
    assert!(
        out.contains("src/a.ts:1  duplicates src/c.ts:1-16"),
        "{out}"
    );
}

// csharp-analysis: "Generated C# files are skipped": a skipped file
// takes no part in duplication, unchanged or deleted.
#[test]
fn files_generated_by_header_take_no_part_in_duplication() {
    let generated = format!("// <auto-generated />\n{}", cs_calls());
    // Unchanged: a copy of it is no copy.
    let out = run(
        &[("src/Snapshot.cs", &generated)],
        &[("src/Copy.cs", Some(&cs_calls()))],
    );
    assert_eq!(out, "No regressions found.\n");
    let out = run(
        &[("src/Snapshot.cs", &cs_calls())],
        &[("src/Copy.cs", Some(&cs_calls()))],
    );
    assert!(out.contains(COPY_RULE), "{out}");
    // Deleted: it held no copy before. Its other code keeps git from
    // taking the deletion and the new file for a rename.
    let deleted = format!("{generated}{}", complex_class("Big"));
    let out = run(
        &[("src/Other.cs", &cs_calls()), ("src/Gen.cs", &deleted)],
        &[("src/Gen.cs", None), ("src/Copy.cs", Some(&cs_calls()))],
    );
    assert!(
        out.contains("src/Copy.cs:1  duplicates src/Other.cs:1-22"),
        "{out}"
    );
}

// A file that becomes generated: its old code left, so moving that code
// elsewhere is no new copy (design D5).
#[test]
fn a_file_that_becomes_generated_keeps_its_old_code() {
    let out = run(
        &[
            ("src/Format.cs", &cs_calls()),
            ("src/Other.cs", &cs_calls()),
        ],
        &[
            (
                "src/Format.cs",
                Some("// <auto-generated />\nclass Format { }\n"),
            ),
            ("src/New.cs", Some(&cs_calls())),
        ],
    );
    assert_eq!(out, "No regressions found.\n");
}

